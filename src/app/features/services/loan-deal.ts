import { Injectable } from '@angular/core';
import { HttpClient, HttpParams } from '@angular/common/http';
import { Observable } from 'rxjs';
import {
  ApiResponse,
  ApplyLoanRequest,
  ApplyLoanResponse,
  LoanTypeOption,
  ReviewDealRequest
} from '../models/loan-deal.model';

export interface CustomerEligibilityResult {
  customerId: number;
  customerName: string;
  cibilScore: number | null;
  eligible: boolean | null;
  eligibleLoanAmount: number | null;
  rejectionReason: string | null;
}

@Injectable({
  providedIn: 'root'
})
export class LoanDealService {
  private readonly baseUrl = 'http://localhost:8080/api/loans';
  private readonly eligibilityUrl = 'http://localhost:8080/api/v1/user/eligibility/result';

  constructor(private http: HttpClient) {}

  // Fetch the evaluated eligibility limit generated by TL's scorecard module
  getCustomerEligibility(customerId: number): Observable<ApiResponse<CustomerEligibilityResult>> {
    const params = new HttpParams().set('customerId', customerId.toString());
    return this.http.get<ApiResponse<CustomerEligibilityResult>>(this.eligibilityUrl, { params });
  }

  getAvailableLoanTypes(): Observable<ApiResponse<LoanTypeOption[]>> {
    return this.http.get<ApiResponse<LoanTypeOption[]>>(`${this.baseUrl}/types`);
  }

  applyLoan(payload: ApplyLoanRequest): Observable<ApiResponse<ApplyLoanResponse>> {
    return this.http.post<ApiResponse<ApplyLoanResponse>>(`${this.baseUrl}/apply`, payload);
  }

  getCustomerApplications(customerId: number): Observable<ApiResponse<ApplyLoanResponse[]>> {
    return this.http.get<ApiResponse<ApplyLoanResponse[]>>(`${this.baseUrl}/customer/${customerId}`);
  }

  getPendingDeals(): Observable<ApiResponse<ApplyLoanResponse[]>> {
    return this.http.get<ApiResponse<ApplyLoanResponse[]>>(`${this.baseUrl}/pending`);
  }

  reviewDeal(dealId: number, payload: ReviewDealRequest): Observable<ApiResponse<ApplyLoanResponse>> {
    return this.http.put<ApiResponse<ApplyLoanResponse>>(`${this.baseUrl}/${dealId}/review`, payload);
  }
}